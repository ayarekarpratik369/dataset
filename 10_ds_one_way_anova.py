# ================================================================
# EXPERIMENT: ONE-WAY ANOVA AND TUKEY'S HSD POST-HOC TEST
#
# Dataset: Student Performance in Exams
# Independent variable: Parental level of education
# Dependent variable: Mathematics score
#
# Statistical methods:
#   1. Descriptive statistics
#   2. One-Way ANOVA
#   3. Tukey's HSD post-hoc test
#   4. Visualization and interpretation
# ================================================================


# STEP 1: IMPORT REQUIRED LIBRARIES

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

from scipy.stats import f_oneway
from statsmodels.stats.multicomp import pairwise_tukeyhsd

# STEP 2: LOAD THE DATASET

url = ("https://raw.githubusercontent.com/"
"ayarekarpratik369/dataset/main/10_students_performance.csv")

df = pd.read_csv(url)

print("=" * 75)
print("STUDENT PERFORMANCE DATASET")
print("=" * 75)

print("\nFirst five records:")
print(df.head())

print("\nDataset shape:", df.shape)

print("\nColumn names:")
print(df.columns.tolist())

# STEP 3: SELECT THE REQUIRED VARIABLES

# Independent variable:
# Parental level of education (categorical, six groups)
#
# Dependent variable:
# Mathematics score (numerical)

group_column = "parental level of education"
score_column = "math score"

# Keep only the columns required for this experiment.
data = df[[group_column, score_column]].copy()

# Remove missing values in the selected columns.
data.dropna(subset=[group_column, score_column], inplace=True)

# Ensure that mathematics scores are numeric.
data[score_column] = pd.to_numeric(
    data[score_column],
    errors="coerce"
)

data.dropna(subset=[score_column], inplace=True)

print("\nNumber of usable observations:", len(data))

print("\nEducation groups:")
print(data[group_column].unique())

# STEP 4: FORMULATE THE HYPOTHESES

# Null hypothesis (H0):
# All six parental education groups have equal population
# mean mathematics scores.
#
# Alternative hypothesis (H1):
# At least one group has a different population mean.


alpha = 0.05

print("\n" + "=" * 75)
print("STEP 4: HYPOTHESIS TESTING")
print("=" * 75)

print("H0: All group mean mathematics scores are equal.")
print("H1: At least one group mean is different.")
print("Significance level (alpha):", alpha)

# STEP 5: CALCULATE DESCRIPTIVE STATISTICS

group_summary = data.groupby(group_column)[score_column].agg(
    ["count", "mean", "std", "median"]
).round(3)

print("\n" + "=" * 75)
print("STEP 5: DESCRIPTIVE STATISTICS")
print("=" * 75)

print(group_summary)

# STEP 6: PREPARE THE GROUPS FOR ONE-WAY ANOVA

groups = [
    group[score_column].to_numpy()
    for _, group in data.groupby(group_column, sort=True)
]

group_names = sorted(data[group_column].unique())

print("\nNumber of groups:", len(groups))

for name, group in zip(group_names, groups):
    print(
        f"{name}: n = {len(group)}, "
        f"mean = {np.mean(group):.3f}"
    )

# STEP 7: PERFORM ONE-WAY ANOVA

f_statistic, p_value = f_oneway(*groups)

print("\n" + "=" * 75)
print("STEP 7: ONE-WAY ANOVA RESULTS")
print("=" * 75)

print(f"F-statistic: {f_statistic:.4f}")
print(f"P-value:     {p_value:.8f}")

if p_value < alpha:
    print("\nDecision: Reject the null hypothesis.")
    print(
        "Conclusion: There is statistically significant evidence "
        "that not all group mean mathematics scores are equal."
    )
else:
    print("\nDecision: Fail to reject the null hypothesis.")
    print(
        "Conclusion: The test does not provide sufficient evidence "
        "of a difference among the group means."
    )

# STEP 8: PERFORM TUKEY'S HSD POST-HOC TEST

# Tukey's HSD compares every pair of group means.
# It adjusts for multiple comparisons to control the family-wise
# Type I error rate.

tukey = pairwise_tukeyhsd(
    endog=data[score_column],
    groups=data[group_column],
    alpha=alpha
)

print("\n" + "=" * 75)
print("STEP 8: TUKEY'S HSD POST-HOC RESULTS")
print("=" * 75)

print(tukey)

# STEP 9: CONVERT TUKEY RESULTS INTO A DATAFRAME

tukey_table = pd.DataFrame(
    data=tukey._results_table.data[1:],
    columns=tukey._results_table.data[0]
)

# Convert numerical columns from strings to numeric values.
for column in [
    "meandiff",
    "p-adj",
    "lower",
    "upper"
]:
    tukey_table[column] = pd.to_numeric(
        tukey_table[column]
    )

tukey_table["reject"] = (
    tukey_table["reject"]
    .astype(str)
    .str.lower()
    .map({"true": True, "false": False})
)

print("\nReadable Tukey HSD comparison table:")
print(tukey_table.to_string(index=False))

# STEP 10: IDENTIFY SIGNIFICANT GROUP PAIRS

significant_pairs = tukey_table[
    tukey_table["reject"] == True
]

print("\n" + "=" * 75)
print("STEP 10: SIGNIFICANT GROUP DIFFERENCES")
print("=" * 75)

if len(significant_pairs) > 0:
    print(
        "The following group pairs have statistically significant "
        "differences in mean mathematics scores:"
    )

    for _, row in significant_pairs.iterrows():
        print(
            f"\nGroup 1: {row['group1']}"
            f"\nGroup 2: {row['group2']}"
            f"\nMean difference (group2 - group1): "
            f"{row['meandiff']:.3f}"
            f"\nAdjusted p-value: {row['p-adj']:.5f}"
            f"\n95% confidence interval: "
            f"[{row['lower']:.3f}, {row['upper']:.3f}]"
        )

else:
    print(
        "No group pairs showed statistically significant "
        "differences after Tukey's HSD adjustment."
    )

# STEP 11: VISUALIZE THE DISTRIBUTION USING A BOX PLOT

plt.figure(figsize=(13, 7))

sns.boxplot(
    data=data,
    x=group_column,
    y=score_column
)

plt.title(
    "Mathematics Score Distribution by Parental Education"
)

plt.xlabel("Parental Level of Education")
plt.ylabel("Mathematics Score")

plt.xticks(rotation=30, ha="right")
plt.tight_layout()
plt.show()

# STEP 12: VISUALIZE GROUP MEANS

mean_scores = (
    data.groupby(group_column)[score_column]
    .mean()
    .sort_values(ascending=False)
)

plt.figure(figsize=(12, 6))

sns.barplot(
    x=mean_scores.index,
    y=mean_scores.values
)

plt.title(
    "Average Mathematics Score by Parental Education"
)

plt.xlabel("Parental Level of Education")
plt.ylabel("Mean Mathematics Score")

plt.xticks(rotation=30, ha="right")
plt.tight_layout()
plt.show()

# STEP 13: DISPLAY FINAL CONCLUSION

print("\n" + "=" * 75)
print("FINAL CONCLUSION")
print("=" * 75)

if p_value < alpha:
    print(
        "One-Way ANOVA found evidence of a difference in mean "
        "mathematics scores across parental education groups."
    )

    if len(significant_pairs) > 0:
        print(
            "Tukey's HSD identified the specific pairs with "
            "statistically significant differences."
        )
    else:
        print(
            "However, Tukey's HSD did not identify any individual "
            "pair as significant at the chosen significance level."
        )

else:
    print(
        "One-Way ANOVA did not find sufficient evidence that "
        "the population mean mathematics scores differ among "
        "parental education groups."
    )

print("\nExperiment completed successfully.")