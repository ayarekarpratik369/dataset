# ================================================================
# LAB EXPERIMENT: TIME SERIES DECOMPOSITION AND FORECASTING
#
# Dataset: Retail Sales (uploaded CSV: retail_sales_dataset.csv)
# Techniques:
# 1. Time Series Decomposition
# 2. Naive Forecasting Baseline
# 3. Holt-Winters Exponential Smoothing
#
# Evaluation Metrics:
# 1. MAPE - Mean Absolute Percentage Error
# 2. RMSE - Root Mean Squared Error
#
# NOTE:
# The CSV contains individual transactions from Jan 2023 to Jan 2024
# (only about 12 months). Yearly (period=12) seasonality needs at
# least 24 months, so this experiment aggregates sales DAILY and
# uses WEEKLY seasonality (period=7) instead.
# ================================================================


# ================================================================
# STEP 1: IMPORT REQUIRED LIBRARIES
# ================================================================

import os
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

from statsmodels.tsa.seasonal import seasonal_decompose
from statsmodels.tsa.holtwinters import ExponentialSmoothing

from sklearn.metrics import mean_squared_error

# ================================================================
# STEP 2: LOAD THE RETAIL SALES DATASET FROM THE UPLOADED CSV
# ================================================================

print("\n" + "=" * 65)
print("TIME SERIES DECOMPOSITION AND FORECASTING")
print("=" * 65)

url = ("https://raw.githubusercontent.com/"
       "ayarekarpratik369/dataset/main/7_retail_sales_dataset.csv")



df = pd.read_csv(url)

print("\nSTEP 2: DATASET LOADED")
print("-" * 65)

print("\nFirst Five Records:")
print(df.head())

print("\nDataset Shape:")
print(df.shape)

print("\nDataset Columns:")
print(df.columns.tolist())

# ================================================================
# STEP 3: DATA CLEANING AND DAILY AGGREGATION
# ================================================================

print("\nSTEP 3: DATA CLEANING")
print("-" * 65)

# Remove rows with missing dates or sales amounts.

df = df.dropna(subset=["Date", "Total Amount"])

# Convert dates into datetime format.

df["Date"] = pd.to_datetime(df["Date"], errors="coerce")
df = df.dropna(subset=["Date"])

# Keep only positive sales amounts.

df = df[df["Total Amount"] > 0]

# The last month (Jan 2024) has only one day of data, which would
# distort the series, so keep only complete 2023 data.

df = df[df["Date"] < "2024-01-01"]

# Aggregate Total Amount by day.
# Days with no transactions are filled with 0 so the series has
# a regular daily frequency (required by the models).

daily_sales = (
    df.set_index("Date")["Total Amount"]
    .resample("D")
    .sum()
    .asfreq("D", fill_value=0)
)

print("\nDaily Retail Sales:")
print(daily_sales.head())

print("\nNumber of Daily Observations:", len(daily_sales))
print("Days with zero sales:", int((daily_sales == 0).sum()))

# ================================================================
# STEP 4: VISUALIZE THE ORIGINAL TIME SERIES
# ================================================================

print("\nSTEP 4: ORIGINAL TIME SERIES")
print("-" * 65)

plt.figure(figsize=(12, 5))

plt.plot(daily_sales.index, daily_sales.values, linewidth=1)

plt.title("Daily Retail Sales")
plt.xlabel("Date")
plt.ylabel("Total Sales Amount")
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.show()

# ================================================================
# STEP 5: DECOMPOSE THE TIME SERIES
# ================================================================

print("\nSTEP 5: TIME SERIES DECOMPOSITION")
print("-" * 65)

# Trend: Long-term direction of sales.
# Seasonality: Repeating weekly pattern.
# Residual: Remaining variation not explained by trend/seasonality.
#
# period=7 means a weekly seasonal cycle in daily data.
#
# Additive decomposition is used here:
# Observed = Trend + Seasonal + Residual
# (Multiplicative is not possible because the series contains zeros.)

decomposition = seasonal_decompose(
    daily_sales,
    model="additive",
    period=7,
    extrapolate_trend="freq"
)

fig = decomposition.plot()
fig.set_size_inches(12, 9)

plt.suptitle(
    "Retail Sales Time Series Decomposition",
    fontsize=15,
    y=1.02
)

plt.tight_layout()
plt.show()

print("Trend, seasonal, and residual components plotted successfully.")

# ================================================================
# STEP 6: PREPARE TRAINING AND TESTING DATA
# ================================================================

print("\nSTEP 6: TRAIN-TEST SPLIT")
print("-" * 65)

# Keep the last 30 days for testing.
# All earlier days are used for training.
#
# Time series must be split chronologically.
# Random splitting would leak future information into training.

test_size = 30

if len(daily_sales) <= 2 * test_size:
    raise ValueError("Not enough observations for this experiment.")

train = daily_sales.iloc[:-test_size]
test = daily_sales.iloc[-test_size:]

print("Training Observations:", len(train))
print("Testing Observations:", len(test))

print("\nTest Period:")
print(test.index.min(), "to", test.index.max())

# ================================================================
# STEP 7: NAIVE FORECASTING BASELINE
# ================================================================

print("\nSTEP 7: NAIVE FORECASTING")
print("-" * 65)

# Naive forecast:
# Every future prediction equals the last observed training value.
#
# This is a simple baseline against which advanced models are
# compared.

last_train_value = train.iloc[-1]

naive_forecast = pd.Series(
    [last_train_value] * len(test),
    index=test.index,
    name="Naive Forecast"
)

print("\nNaive Forecast Values (first 5):")
print(naive_forecast.head())

# ================================================================
# STEP 8: HOLT-WINTERS EXPONENTIAL SMOOTHING
# ================================================================

print("\nSTEP 8: HOLT-WINTERS FORECASTING")
print("-" * 65)

# Holt-Winters Exponential Smoothing models:
# 1. Level
# 2. Trend
# 3. Seasonality
#
# Seasonal period = 7 for daily observations (weekly pattern).
#
# Additive trend and seasonality are used because the data has
# zero values (multiplicative models require strictly positive data).

hw_model = ExponentialSmoothing(
    train,
    trend="add",
    seasonal="add",
    seasonal_periods=7,
    initialization_method="estimated"
)

hw_fitted = hw_model.fit(optimized=True)

# Forecast the next 30 days.

hw_forecast = hw_fitted.forecast(len(test))
hw_forecast.name = "Holt-Winters Forecast"

print("\nHolt-Winters Forecast Values (first 5):")
print(hw_forecast.head())

# ================================================================
# STEP 9: EVALUATE FORECASTS USING MAPE AND RMSE
# ================================================================

print("\nSTEP 9: FORECAST EVALUATION")
print("-" * 65)

# MAPE = mean absolute percentage error.
# Lower MAPE indicates smaller percentage forecast errors.
#
# RMSE = square root of mean squared error.
# Lower RMSE indicates smaller errors, with larger errors penalized.
#
# MAPE is undefined when the actual value is zero, so zero actual
# days are excluded from the MAPE calculation.

def calculate_mape(actual, predicted):

    actual = np.asarray(actual, dtype=float)
    predicted = np.asarray(predicted, dtype=float)

    nonzero_mask = actual != 0

    if not np.any(nonzero_mask):
        return np.nan

    return np.mean(
        np.abs(
            (actual[nonzero_mask] - predicted[nonzero_mask])
            / actual[nonzero_mask]
        )
    ) * 100


def calculate_rmse(actual, predicted):

    return np.sqrt(mean_squared_error(actual, predicted))


# Naive model metrics.

naive_mape = calculate_mape(test.values, naive_forecast.values)
naive_rmse = calculate_rmse(test.values, naive_forecast.values)

# Holt-Winters model metrics.

hw_mape = calculate_mape(test.values, hw_forecast.values)
hw_rmse = calculate_rmse(test.values, hw_forecast.values)

# ================================================================
# STEP 10: DISPLAY THE FINAL COMPARISON
# ================================================================

print("\nSTEP 10: MODEL COMPARISON")
print("-" * 65)

comparison = pd.DataFrame({
    "Model": [
        "Naive Baseline",
        "Holt-Winters Exponential Smoothing"
    ],
    "MAPE (%)": [naive_mape, hw_mape],
    "RMSE": [naive_rmse, hw_rmse]
})

print(comparison.round(3).to_string(index=False))

# ================================================================
# STEP 11: PLOT ACTUAL VS PREDICTED VALUES
# ================================================================

print("\nSTEP 11: ACTUAL VS PREDICTED SALES")
print("-" * 65)

plt.figure(figsize=(13, 6))

# Actual sales.

plt.plot(
    test.index, test.values,
    marker="o", linewidth=2, label="Actual Sales"
)

# Naive predictions.

plt.plot(
    naive_forecast.index, naive_forecast.values,
    marker="s", linestyle="--", label="Naive Forecast"
)

# Holt-Winters predictions.

plt.plot(
    hw_forecast.index, hw_forecast.values,
    marker="^", linestyle="--", label="Holt-Winters Forecast"
)

plt.title("Actual vs Predicted Daily Retail Sales")
plt.xlabel("Date")
plt.ylabel("Total Sales Amount")
plt.legend()
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.show()

# ================================================================
# STEP 12: PLOT FORECAST ERROR COMPARISON
# ================================================================

print("\nSTEP 12: FORECAST ERROR COMPARISON")
print("-" * 65)

fig, axes = plt.subplots(1, 2, figsize=(12, 5))

# Compare MAPE.

axes[0].bar(comparison["Model"], comparison["MAPE (%)"])
axes[0].set_title("MAPE Comparison")
axes[0].set_ylabel("MAPE (%)")
axes[0].tick_params(axis="x", rotation=15)

# Compare RMSE.

axes[1].bar(comparison["Model"], comparison["RMSE"])
axes[1].set_title("RMSE Comparison")
axes[1].set_ylabel("RMSE")
axes[1].tick_params(axis="x", rotation=15)

plt.tight_layout()
plt.show()

# ================================================================
# STEP 13: FINAL CONCLUSION
# ================================================================

print("\nSTEP 13: FINAL CONCLUSION")
print("=" * 65)

if hw_mape < naive_mape and hw_rmse < naive_rmse:
    print("Holt-Winters performed better than the Naive baseline "
          "on both MAPE and RMSE.")

elif naive_mape < hw_mape and naive_rmse < hw_rmse:
    print("The Naive baseline performed better than Holt-Winters "
          "on both MAPE and RMSE.")

else:
    print("The models have mixed results. Compare both MAPE and RMSE "
          "to understand their forecasting performance.")

print("\nFinal Metrics:")
print(comparison.round(3).to_string(index=False))

print("\nLAB EXPERIMENT COMPLETED SUCCESSFULLY!")
print("=" * 65)