# ================================================================
# PROJECT: MALL CUSTOMER SEGMENTATION USING K-MEANS
#
# DATASET: Mall_Customers.csv
#
# OBJECTIVES:
# 1. Preprocess customer data
# 2. Scale numerical features
# 3. Find optimal clusters using Elbow Method
# 4. Find optimal clusters using Silhouette Score
# 5. Apply K-Means clustering
# 6. Visualize clusters and their boundaries
# 7. Interpret customer segments for business decisions
# ================================================================


# ================================================================
# STEP 1: IMPORT REQUIRED LIBRARIES
# ================================================================

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.preprocessing import StandardScaler
from sklearn.cluster import KMeans
from sklearn.metrics import silhouette_score

# ================================================================
# STEP 2: LOAD THE DATASET
# ================================================================

print("\n" + "=" * 70)
print("MALL CUSTOMER SEGMENTATION USING K-MEANS")
print("=" * 70)

# Download Mall_Customers.csv from Kaggle and place it
# in the same folder as this Python script.

url = ("https://raw.githubusercontent.com/"
        "ayarekarpratik369/dataset/main/8_Mall_Customers.csv"
)

df = pd.read_csv(url)

print("\nSTEP 2: DATASET LOADED")
print("-" * 70)

print("\nFirst Five Records:")
print(df.head())

print("\nDataset Shape:")
print(df.shape)

print("\nColumn Names:")
print(df.columns.tolist())

print("\nDataset Information:")
df.info()

# ================================================================
# STEP 3: DATA PREPROCESSING
# ================================================================

print("\nSTEP 3: DATA PREPROCESSING")
print("-" * 70)

# Check missing values.

print("\nMissing Values:")
print(df.isnull().sum())

# Check duplicate records.

print("\nDuplicate Rows:", df.duplicated().sum())

# Remove duplicate records if present.

df = df.drop_duplicates().copy()

# Remove rows with missing values in the required features.

required_columns = [
    "Age",
    "Annual Income (k$)",
    "Spending Score (1-100)"
]

df = df.dropna(subset=required_columns).copy()

# CustomerID is only an identifier, not a meaningful clustering feature.
# Gender is excluded to focus segmentation on customer age,
# annual income, and spending behavior.
#
# These choices are intentional. Other feature combinations
# may produce different customer segments.

features = [
    "Age",
    "Annual Income (k$)",
    "Spending Score (1-100)"
]

X = df[features].copy()

print("\nSelected Clustering Features:")
print(features)

print("\nCleaned Dataset Shape:")
print(X.shape)

print("\nStatistical Summary:")
print(X.describe())

# ================================================================
# STEP 4: EXPLORE THE CUSTOMER DATA
# ================================================================

print("\nSTEP 4: EXPLORATORY DATA ANALYSIS")
print("-" * 70)

# Plot distributions of the selected numerical features.

X.hist(
    figsize=(12, 7),
    bins=15,
    edgecolor="black"
)

plt.suptitle("Distribution of Customer Features")
plt.tight_layout()
plt.show()

# Plot relationships between income and spending score.

plt.figure(figsize=(8, 6))

sns.scatterplot(
    data=df,
    x="Annual Income (k$)",
    y="Spending Score (1-100)",
    s=70
)

plt.title("Annual Income vs Spending Score")
plt.tight_layout()
plt.show()

# ================================================================
# STEP 5: SCALE THE FEATURES
# ================================================================

print("\nSTEP 5: FEATURE SCALING")
print("-" * 70)

# K-Means uses distances to form clusters.
# Features with larger numerical scales can dominate those distances.
#
# StandardScaler transforms each feature to approximately:
# mean = 0
# standard deviation = 1

scaler = StandardScaler()

X_scaled = scaler.fit_transform(X)

print("Feature scaling completed successfully.")

scaled_df = pd.DataFrame(
    X_scaled,
    columns=features,
    index=X.index
)

print("\nFirst Five Scaled Records:")
print(scaled_df.head())

# ================================================================
# STEP 6: DETERMINE OPTIMAL K USING THE ELBOW METHOD
# ================================================================

print("\nSTEP 6: ELBOW METHOD")
print("-" * 70)

# Inertia is the sum of squared distances between each data point
# and its assigned cluster center.
#
# Inertia always decreases as the number of clusters increases.
# Look for the point where the decrease begins to slow noticeably.

k_values = range(1, 11)

inertia_values = []

for k in k_values:

    model = KMeans(
        n_clusters=k,
        random_state=42,
        n_init=10
    )

    model.fit(X_scaled)

    inertia_values.append(model.inertia_)

# Plot the Elbow curve.

plt.figure(figsize=(8, 5))

plt.plot(
    list(k_values),
    inertia_values,
    marker="o"
)

plt.title("Elbow Method for Optimal K")
plt.xlabel("Number of Clusters (K)")
plt.ylabel("Inertia (WCSS)")
plt.xticks(list(k_values))
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.show()

# ================================================================
# STEP 7: DETERMINE OPTIMAL K USING SILHOUETTE SCORE
# ================================================================

print("\nSTEP 7: SILHOUETTE SCORE ANALYSIS")
print("-" * 70)

# Silhouette Score ranges from -1 to +1.
#
# Higher values generally indicate better-separated clusters.
# Negative values can indicate that observations are assigned
# to clusters that do not fit them well.
#
# Silhouette Score is defined only when there are at least
# 2 clusters and fewer clusters than data points.

silhouette_values = {}

for k in range(2, 11):

    model = KMeans(
        n_clusters=k,
        random_state=42,
        n_init=10
    )

    labels = model.fit_predict(X_scaled)

    score = silhouette_score(X_scaled, labels)

    silhouette_values[k] = score

    print(f"K = {k:2d} | Silhouette Score = {score:.4f}")


# Plot Silhouette Scores.

plt.figure(figsize=(8, 5))

plt.plot(
    list(silhouette_values.keys()),
    list(silhouette_values.values()),
    marker="o"
)

plt.title("Silhouette Score for Different K Values")
plt.xlabel("Number of Clusters (K)")
plt.ylabel("Silhouette Score")
plt.xticks(list(silhouette_values.keys()))
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.show()

# Find the K with the highest Silhouette Score.

best_silhouette_k = max(
    silhouette_values,
    key=silhouette_values.get
)

print("\nK with Highest Silhouette Score:", best_silhouette_k)

# ================================================================
# STEP 8: SELECT THE FINAL NUMBER OF CLUSTERS
# ================================================================

print("\nSTEP 8: SELECT FINAL K")
print("-" * 70)

# The highest Silhouette Score is a useful candidate, but it should
# not automatically determine K by itself.
#
# Examine the Elbow curve and Silhouette curve together.
#
# For this educational dataset, K=5 is a common starting choice
# when grouping customers by income and spending behavior.
#
# Because this implementation includes Age as a third feature,
# the best choice may differ. Review both plots and adjust K
# below if your analysis supports a different value.

FINAL_K = 5

print("Selected Number of Clusters:", FINAL_K)
print("Highest Silhouette Score K:", best_silhouette_k)

print(
    "Check the Elbow and Silhouette plots to justify "
    "the selected FINAL_K in your report."
)

# ================================================================
# STEP 9: APPLY THE FINAL K-MEANS MODEL
# ================================================================

print("\nSTEP 9: K-MEANS CLUSTERING")
print("-" * 70)

kmeans = KMeans(
    n_clusters=FINAL_K,
    random_state=42,
    n_init=10
)

# Fit the model and assign a cluster label to each customer.

df["Cluster"] = kmeans.fit_predict(X_scaled)

# Calculate the final silhouette score.

final_silhouette = silhouette_score(
    X_scaled,
    df["Cluster"]
)

print("K-Means clustering completed successfully.")
print("Final Number of Clusters:", FINAL_K)
print(f"Final Silhouette Score: {final_silhouette:.4f}")

print("\nCustomer Cluster Assignments:")
print(
    df[
        [
            "CustomerID",
            "Age",
            "Annual Income (k$)",
            "Spending Score (1-100)",
            "Cluster"
        ]
    ].head(10)
)

# ================================================================
# STEP 10: VISUALIZE CLUSTERS IN TWO DIMENSIONS
# ================================================================

print("\nSTEP 10: CUSTOMER CLUSTER VISUALIZATION")
print("-" * 70)

# Plot annual income against spending score.
#
# Since the model uses three features, the 2D scatter plot is
# a projection of the clusters. Some points may overlap because
# age is not displayed on these axes.

plt.figure(figsize=(10, 7))

sns.scatterplot(
    data=df,
    x="Annual Income (k$)",
    y="Spending Score (1-100)",
    hue="Cluster",
    palette="tab10",
    s=90,
    alpha=0.85
)

# Transform cluster centers back to original feature units
# so the centroids can be displayed on the original-scale plot.

centers_original = scaler.inverse_transform(
    kmeans.cluster_centers_
)

# Column index 1 = annual income.
# Column index 2 = spending score.

plt.scatter(
    centers_original[:, 1],
    centers_original[:, 2],
    marker="X",
    s=250,
    c="black",
    label="Cluster Centers"
)

plt.title("Mall Customer Segments")
plt.xlabel("Annual Income (k$)")
plt.ylabel("Spending Score (1-100)")
plt.legend()
plt.tight_layout()
plt.show()

# ================================================================
# STEP 11: VISUALIZE CLUSTER BOUNDARIES
# ================================================================

print("\nSTEP 11: CLUSTER BOUNDARIES")
print("-" * 70)

# For a readable 2D boundary plot, fit another K-Means model using
# only annual income and spending score.
#
# This is a separate 2D visualization model. Its labels are not
# necessarily identical to the three-feature model from Step 9.
#
# The 2D model helps visualize the regions separated by K-Means.

boundary_features = [
    "Annual Income (k$)",
    "Spending Score (1-100)"
]

X_2d = df[boundary_features].copy()

scaler_2d = StandardScaler()

X_2d_scaled = scaler_2d.fit_transform(X_2d)

kmeans_2d = KMeans(
    n_clusters=FINAL_K,
    random_state=42,
    n_init=10
)

labels_2d = kmeans_2d.fit_predict(X_2d_scaled)

# Build a mesh grid covering the feature space.

x_min, x_max = X_2d_scaled[:, 0].min() - 0.5, X_2d_scaled[:, 0].max() + 0.5
y_min, y_max = X_2d_scaled[:, 1].min() - 0.5, X_2d_scaled[:, 1].max() + 0.5

xx, yy = np.meshgrid(
    np.arange(x_min, x_max, 0.02),
    np.arange(y_min, y_max, 0.02)
)

# Predict the cluster for every point in the mesh.

grid_points = np.c_[xx.ravel(), yy.ravel()]

Z = kmeans_2d.predict(grid_points)

Z = Z.reshape(xx.shape)

# Plot the background cluster regions and customer observations.

plt.figure(figsize=(10, 7))

plt.contourf(
    xx,
    yy,
    Z,
    alpha=0.25,
    cmap="tab10"
)

plt.scatter(
    X_2d_scaled[:, 0],
    X_2d_scaled[:, 1],
    c=labels_2d,
    cmap="tab10",
    edgecolor="black",
    s=60
)

# Plot centroids.

centers_2d = kmeans_2d.cluster_centers_

plt.scatter(
    centers_2d[:, 0],
    centers_2d[:, 1],
    marker="X",
    s=250,
    c="black",
    label="Centroids"
)

plt.title("K-Means Cluster Boundaries (Income vs Spending)")
plt.xlabel("Standardized Annual Income")
plt.ylabel("Standardized Spending Score")
plt.legend()
plt.tight_layout()
plt.show()

# ================================================================
# STEP 12: ANALYZE CUSTOMER SEGMENTS
# ================================================================

print("\nSTEP 12: CUSTOMER SEGMENT ANALYSIS")
print("-" * 70)

# Calculate average age, income, spending score, and customer count
# for each cluster using the original feature units.

cluster_summary = (
    df.groupby("Cluster")
    .agg(
        Customer_Count=("CustomerID", "count"),
        Average_Age=("Age", "mean"),
        Average_Income=("Annual Income (k$)", "mean"),
        Average_Spending_Score=("Spending Score (1-100)", "mean")
    )
    .round(2)
)

print("\nCluster Summary:")
print(cluster_summary)

# ================================================================
# STEP 13: INTERPRET CLUSTERS IN A BUSINESS CONTEXT
# ================================================================

print("\nSTEP 13: BUSINESS INTERPRETATION")
print("-" * 70)

# Use relative income and spending levels to assign descriptive
# segment names. These names are interpretations, not labels
# supplied by the dataset.

income_median = df["Annual Income (k$)"].median()
spending_median = df["Spending Score (1-100)"].median()

for cluster_id, row in cluster_summary.iterrows():

    avg_income = row["Average_Income"]
    avg_spending = row["Average_Spending_Score"]
    avg_age = row["Average_Age"]
    count = int(row["Customer_Count"])

    if avg_income >= income_median and avg_spending >= spending_median:

        segment_name = "High-Income, High-Spending Customers"

        strategy = (
            "Offer loyalty rewards, premium products, "
            "exclusive offers, and VIP membership benefits."
        )

    elif avg_income >= income_median and avg_spending < spending_median:

        segment_name = "High-Income, Low-Spending Customers"

        strategy = (
            "Use personalized recommendations, product demonstrations, "
            "and targeted promotions to encourage purchases."
        )

    elif avg_income < income_median and avg_spending >= spending_median:

        segment_name = "Lower-Income, High-Spending Customers"

        strategy = (
            "Promote attractive bundles, loyalty points, "
            "and limited-time offers."
        )

    else:

        segment_name = "Lower-Income, Low-Spending Customers"

        strategy = (
            "Use budget-friendly products, value packs, "
            "and low-cost engagement campaigns."
        )

    print(f"\nCluster {cluster_id}: {segment_name}")
    print(f"Number of Customers: {count}")
    print(f"Average Age: {avg_age:.2f}")
    print(f"Average Annual Income: {avg_income:.2f} k$")
    print(f"Average Spending Score: {avg_spending:.2f}")
    print("Suggested Business Strategy:", strategy)

# ================================================================
# STEP 14: EXPORT THE FINAL CUSTOMER SEGMENTS
# ================================================================

print("\nSTEP 14: EXPORT RESULTS")
print("-" * 70)

# Save the customer records with their assigned cluster labels.

df.to_csv(
    "mall_customer_segments.csv",
    index=False
)

# Save the cluster summary separately.

cluster_summary.to_csv(
    "mall_cluster_summary.csv"
)

print("Customer assignments saved to mall_customer_segments.csv")
print("Cluster summary saved to mall_cluster_summary.csv")

# ================================================================
# STEP 15: FINAL CONCLUSION
# ================================================================

print("\nSTEP 15: FINAL CONCLUSION")
print("=" * 70)

print("Dataset preprocessing and feature scaling completed.")
print("Elbow Method and Silhouette Score were used to assess K.")
print("K-Means clustering was applied to customer features.")
print("Cluster visualization and boundary plots were generated.")
print("Customer segments were summarized for business interpretation.")
print("Output CSV files were saved successfully.")

print("\nFINAL SILHOUETTE SCORE:", round(final_silhouette, 4))
print("SELECTED NUMBER OF CLUSTERS:", FINAL_K)

print("\nPROJECT COMPLETED SUCCESSFULLY!")
print("=" * 70)