# STEP 1: IMPORT REQUIRED LIBRARIES

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

sns.set_style("whitegrid")
plt.rcParams["figure.figsize"] = (8, 5)

# STEP 2: LOAD THE DATASET

url = ("https://raw.githubusercontent.com/"
"ayarekarpratik369/dataset/main/1_pima-indians-diabetes.csv")

df = pd.read_csv(url)

print("\nDataset Loaded Successfully!")

# STEP 3: DISPLAY FIRST FIVE RECORDS

print("\nFirst Five Records")
print(df.head())


# STEP 4: CHECK DATASET DIMENSIONS

print("\nDataset Dimensions")
print("Number of Rows:", df.shape[0])
print("Number of Columns:", df.shape[1])


# STEP 5: CHECK DATA TYPES AND NON-NULL COUNTS

print("\nDataset Information")
df.info()

# STEP 6: GENERATE STATISTICAL SUMMARY

print("\nSTEP 6: Statistical Summary")
print(df.describe())


# STEP 7: CHECK MISSING VALUES

print("\nSTEP 7: Missing Values")
print(df.isnull().sum())


# STEP 8: CHECK ZERO VALUES IN MEDICAL MEASUREMENTS

print("\nSTEP 8: Zero Values in Medical Measurements")

medical_columns = [
    "Glucose", "BloodPressure",
    "SkinThickness", "Insulin", "BMI"
]

for col in medical_columns:
    print(f"{col}: {(df[col] == 0).sum()}")

# Replacing implausible zero measurements with NaN
# Keep the original dataset unchanged

df_clean = df.copy()

df_clean[medical_columns] = (
    df_clean[medical_columns].replace(0, np.nan)
)

print("\nMissing Values After Handling Invalid Zeros:")
print(df_clean.isnull().sum())

# STEP 9: ANALYZE DIABETES OUTCOME

print("\nSTEP 9: Diabetes Outcome Counts")
print(df["Outcome"].value_counts())

sns.countplot(data=df, x="Outcome")
plt.title("Distribution of Diabetes Outcomes")
plt.xlabel("Outcome (0 = No Diabetes, 1 = Diabetes)")
plt.ylabel("Number of Patients")
plt.show()


# STEP 10: ANALYZE AGE DISTRIBUTION

sns.histplot(data=df, x="Age", bins=20, kde=True)
plt.title("Age Distribution of Patients")
plt.xlabel("Age")
plt.ylabel("Frequency")
plt.show()


# STEP 11: ANALYZE GLUCOSE DISTRIBUTION

sns.histplot(data=df_clean, x="Glucose", bins=25, kde=True)
plt.title("Distribution of Glucose Levels")
plt.xlabel("Glucose Level")
plt.ylabel("Frequency")
plt.show()


# STEP 12: COMPARE GLUCOSE LEVELS BY DIABETES OUTCOME

sns.boxplot(data=df_clean, x="Outcome", y="Glucose")
plt.title("Glucose Levels by Diabetes Outcome")
plt.xlabel("Outcome (0 = No Diabetes, 1 = Diabetes)")
plt.ylabel("Glucose Level")
plt.show()


# STEP 13: ANALYZE BMI DISTRIBUTION

sns.histplot(data=df_clean, x="BMI", bins=25, kde=True)
plt.title("Distribution of BMI")
plt.xlabel("Body Mass Index (BMI)")
plt.ylabel("Frequency")
plt.show()

# STEP 14: STUDY RELATIONSHIP BETWEEN AGE AND GLUCOSE

sns.scatterplot(
    data=df_clean,
    x="Age",
    y="Glucose",
    hue="Outcome"
)

plt.title("Age vs Glucose Level by Diabetes Outcome")
plt.xlabel("Age")
plt.ylabel("Glucose Level")
plt.show()

# STEP 15: CORRELATION HEATMAP

correlation_matrix = df_clean.corr(numeric_only=True)

sns.heatmap(
    correlation_matrix,
    annot=True,
    cmap="coolwarm",
    fmt=".2f",
    linewidths=0.5
)

plt.title("Correlation Heatmap")
plt.show()

# STEP 16: DETECT POTENTIAL OUTLIERS USING BOX PLOTS

features = [
    "Glucose", "BloodPressure",
    "SkinThickness", "Insulin", "BMI"
]

plt.figure(figsize=(12, 7))

for i, col in enumerate(features, 1):
    plt.subplot(2, 3, i)
    sns.boxplot(data=df_clean, y=col)
    plt.title(f"Box Plot of {col}")

plt.tight_layout()
plt.show()

# STEP 17: COMPARE OUTCOMES ACROSS AGE GROUPS

df_clean["AgeGroup"] = pd.cut(
    df_clean["Age"],
    bins=[20, 30, 40, 50, 60, 100],
    labels=["21-30", "31-40", "41-50", "51-60", "60+"]
)

sns.countplot(
    data=df_clean,
    x="AgeGroup",
    hue="Outcome"
)

plt.title("Diabetes Outcome Across Age Groups")
plt.xlabel("Age Group")
plt.ylabel("Number of Patients")
plt.show()

# STEP 18: FINAL SUMMARY

print("\nSTEP 18: FINAL SUMMARY")

print("Total Records:", df.shape[0])
print("Total Features:", df.shape[1] - 1)
print("Patients Without Diabetes:", (df["Outcome"] == 0).sum())
print("Patients With Diabetes:", (df["Outcome"] == 1).sum())

print("\nEDA Completed Successfully!")