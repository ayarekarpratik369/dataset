# STEP 1: IMPORT REQUIRED LIBRARIES

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.pipeline import Pipeline
from sklearn.naive_bayes import GaussianNB
from sklearn.linear_model import LogisticRegression

from sklearn.metrics import (
    confusion_matrix,
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    roc_auc_score,
    roc_curve,
    classification_report
)

# STEP 2: LOAD THE DATASET

url = ("https://raw.githubusercontent.com/"
        "ayarekarpratik369/dataset/main/9_pima-indians-diabetes.csv"

)

df = pd.read_csv(url)

print("=" * 70)
print("PIMA INDIANS DIABETES DATASET")
print("=" * 70)

print("\nFirst five records:")
print(df.head())

print("\nDataset shape:", df.shape)

print("\nClass distribution:")
print(df["Outcome"].value_counts())

# STEP 3: DATA CLEANING

# In this dataset, zero is not a biologically valid measurement
# for certain medical features. Treat those zeros as missing values.
#
# Do NOT replace zero in Pregnancies or Outcome:
# zero pregnancies and Outcome = 0 are valid values.

zero_missing_columns = [
    "Glucose",
    "BloodPressure",
    "SkinThickness",
    "Insulin",
    "BMI"
]

df[zero_missing_columns] = df[zero_missing_columns].replace(
    0, np.nan
)

print("\nMissing values after correcting invalid zeros:")
print(df.isnull().sum())

# Use median imputation for missing feature values.
# Medians are calculated using the complete dataset here for
# simplicity in the Bayes demonstration. For model evaluation,
# the model-specific imputation pipeline below learns medians
# from training data only.

for column in zero_missing_columns:
    df[column] = df[column].fillna(df[column].median())

# STEP 4: MANUALLY CALCULATE PRIOR PROBABILITIES

# Bayes' Theorem:
#
# P(D | E) = P(E | D) * P(D) / P(E)
#
# D = patient has diabetes
# E = observed evidence

total_patients = len(df)

diabetes_count = int((df["Outcome"] == 1).sum())
no_diabetes_count = int((df["Outcome"] == 0).sum())

# Prior probability P(D)
prior_diabetes = diabetes_count / total_patients

# Prior probability P(not D)
prior_no_diabetes = no_diabetes_count / total_patients

print("\n" + "=" * 70)
print("STEP 4: PRIOR PROBABILITIES")
print("=" * 70)

print(f"Total patients        = {total_patients}")
print(f"Patients with diabetes = {diabetes_count}")
print(f"Patients without diabetes = {no_diabetes_count}")

print(
    f"\nP(Diabetes) = {diabetes_count}/{total_patients}"
    f" = {prior_diabetes:.4f}"
)

print(
    f"P(No Diabetes) = {no_diabetes_count}/{total_patients}"
    f" = {prior_no_diabetes:.4f}"
)

# STEP 5: MANUALLY CALCULATE CONDITIONAL PROBABILITIES

# Select a feature and divide it into categories.
#
# Example:
# Glucose >= 140 is considered the high-glucose category
# for this classroom demonstration.
#
# These are illustrative thresholds, NOT clinical diagnostic rules.

df["High_Glucose"] = (df["Glucose"] >= 140).astype(int)

high_glucose_count = int((df["High_Glucose"] == 1).sum())

high_glucose_diabetes = int(
    (
        (df["High_Glucose"] == 1)
        & (df["Outcome"] == 1)
    ).sum()
)

high_glucose_no_diabetes = int(
    (
        (df["High_Glucose"] == 1)
        & (df["Outcome"] == 0)
    ).sum()
)

# Conditional probability P(E | D)
p_high_given_diabetes = (
    high_glucose_diabetes / diabetes_count
)

# Conditional probability P(E | not D)
p_high_given_no_diabetes = (
    high_glucose_no_diabetes / no_diabetes_count
)

# Marginal probability P(E)
p_high_glucose = high_glucose_count / total_patients

print("\n" + "=" * 70)
print("STEP 5: CONDITIONAL PROBABILITIES")
print("=" * 70)

print(f"Patients with high glucose = {high_glucose_count}")

print(
    "\nP(High Glucose | Diabetes)"
    f" = {high_glucose_diabetes}/{diabetes_count}"
    f" = {p_high_given_diabetes:.4f}"
)

print(
    "P(High Glucose | No Diabetes)"
    f" = {high_glucose_no_diabetes}/{no_diabetes_count}"
    f" = {p_high_given_no_diabetes:.4f}"
)

print(
    "\nP(High Glucose)"
    f" = {high_glucose_count}/{total_patients}"
    f" = {p_high_glucose:.4f}"
)

# STEP 6: APPLY BAYES' THEOREM MANUALLY

# P(Diabetes | High Glucose)
#
# = P(High Glucose | Diabetes) * P(Diabetes)
#   ------------------------------------------------
#                P(High Glucose)

posterior_diabetes = (
    p_high_given_diabetes * prior_diabetes
) / p_high_glucose

# P(No Diabetes | High Glucose)

posterior_no_diabetes = (
    p_high_given_no_diabetes * prior_no_diabetes
) / p_high_glucose

print("\n" + "=" * 70)
print("STEP 6: BAYES' THEOREM RESULTS")
print("=" * 70)

print(
    "P(Diabetes | High Glucose)"
    f" = {posterior_diabetes:.4f}"
)

print(
    "P(No Diabetes | High Glucose)"
    f" = {posterior_no_diabetes:.4f}"
)

print(
    "\nSum of posterior probabilities ="
    f" {posterior_diabetes + posterior_no_diabetes:.4f}"
)

# STEP 7: DEMONSTRATE CONDITIONAL PROBABILITIES FOR ANOTHER FEATURE

# BMI >= 30 is used as an illustrative category.
# This is not a diagnostic threshold for diabetes.

df["High_BMI"] = (df["BMI"] >= 30).astype(int)

high_bmi_count = int((df["High_BMI"] == 1).sum())

high_bmi_diabetes_count = int(
    (
        (df["High_BMI"] == 1)
        & (df["Outcome"] == 1)
    ).sum()
)

high_bmi_no_diabetes_count = int(
    (
        (df["High_BMI"] == 1)
        & (df["Outcome"] == 0)
    ).sum()
)

p_bmi_given_diabetes = (
    high_bmi_diabetes_count / diabetes_count
)

p_bmi_given_no_diabetes = (
    high_bmi_no_diabetes_count / no_diabetes_count
)

print("\n" + "=" * 70)
print("ADDITIONAL CONDITIONAL PROBABILITY: BMI")
print("=" * 70)

print(
    f"P(High BMI | Diabetes) = "
    f"{high_bmi_diabetes_count}/{diabetes_count} "
    f"= {p_bmi_given_diabetes:.4f}"
)

print(
    f"P(High BMI | No Diabetes) = "
    f"{high_bmi_no_diabetes_count}/{no_diabetes_count} "
    f"= {p_bmi_given_no_diabetes:.4f}"
)

# STEP 8: PREPARE FEATURES AND TARGET

# Exclude the manually created categorical features from model inputs.
# The models use the original numerical medical features.

feature_columns = [
    "Pregnancies",
    "Glucose",
    "BloodPressure",
    "SkinThickness",
    "Insulin",
    "BMI",
    "DiabetesPedigreeFunction",
    "Age"
]

X = pd.read_csv(url)[feature_columns].copy()
y = pd.read_csv(url)["Outcome"].copy()

# Restore invalid zero measurements as missing values.
X[zero_missing_columns] = X[zero_missing_columns].replace(
    0, np.nan
)

# Split before imputation and scaling to avoid test-set leakage.
X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

# STEP 9: BUILD GAUSSIAN NAIVE BAYES MODEL

# Gaussian Naive Bayes estimates a Gaussian distribution
# for each feature within each class.
#
# Missing values are imputed using training medians only.

from sklearn.impute import SimpleImputer

gnb_model = Pipeline([
    ("imputer", SimpleImputer(strategy="median")),
    ("classifier", GaussianNB())
])

# STEP 10: BUILD LOGISTIC REGRESSION MODEL

# Logistic Regression benefits from feature scaling.
# Imputation and scaling are fitted on the training data only.

lr_model = Pipeline([
    ("imputer", SimpleImputer(strategy="median")),
    ("scaler", StandardScaler()),
    ("classifier", LogisticRegression(max_iter=2000))
])

# STEP 11: TRAIN BOTH MODELS

gnb_model.fit(X_train, y_train)
lr_model.fit(X_train, y_train)

print("\n" + "=" * 70)
print("STEP 11: MODEL TRAINING COMPLETED")
print("=" * 70)

print("Gaussian Naive Bayes: Trained successfully")
print("Logistic Regression: Trained successfully")

# STEP 12: PREDICT TEST RESULTS

gnb_predictions = gnb_model.predict(X_test)
lr_predictions = lr_model.predict(X_test)

# Use probability estimates for ROC-AUC, not hard class predictions.

gnb_probabilities = gnb_model.predict_proba(X_test)[:, 1]
lr_probabilities = lr_model.predict_proba(X_test)[:, 1]

# STEP 13: EVALUATE BOTH MODELS

def evaluate_model(model_name, y_true, y_pred, y_prob):
    """Calculate and display standard binary classification metrics."""

    cm = confusion_matrix(y_true, y_pred, labels=[0, 1])

    tn, fp, fn, tp = cm.ravel()

    accuracy = accuracy_score(y_true, y_pred)

    precision = precision_score(
        y_true, y_pred, zero_division=0
    )

    recall = recall_score(
        y_true, y_pred, zero_division=0
    )

    specificity = tn / (tn + fp) if (tn + fp) else 0

    f1 = f1_score(
        y_true, y_pred, zero_division=0
    )

    auc = roc_auc_score(y_true, y_prob)

    print("\n" + "=" * 70)
    print(model_name.upper())
    print("=" * 70)

    print("\nConfusion Matrix:")
    print(cm)

    print("\nConfusion Matrix Interpretation:")
    print(f"True Negatives  (TN) = {tn}")
    print(f"False Positives (FP) = {fp}")
    print(f"False Negatives (FN) = {fn}")
    print(f"True Positives  (TP) = {tp}")

    print(f"\nAccuracy    = {accuracy:.4f}")
    print(f"Precision   = {precision:.4f}")
    print(f"Recall      = {recall:.4f}")
    print(f"Specificity = {specificity:.4f}")
    print(f"F1-Score    = {f1:.4f}")
    print(f"ROC-AUC     = {auc:.4f}")

    print("\nClassification Report:")
    print(
        classification_report(
            y_true,
            y_pred,
            target_names=["No Diabetes", "Diabetes"],
            zero_division=0
        )
    )

    return {
        "Model": model_name,
        "Accuracy": accuracy,
        "Precision": precision,
        "Recall": recall,
        "Specificity": specificity,
        "F1-Score": f1,
        "ROC-AUC": auc,
        "TN": tn,
        "FP": fp,
        "FN": fn,
        "TP": tp
    }


gnb_results = evaluate_model(
    "Gaussian Naive Bayes",
    y_test,
    gnb_predictions,
    gnb_probabilities
)

lr_results = evaluate_model(
    "Logistic Regression",
    y_test,
    lr_predictions,
    lr_probabilities
)

# STEP 14: COMPARE PERFORMANCE METRICS

results_df = pd.DataFrame([
    gnb_results,
    lr_results
])

print("\n" + "=" * 70)
print("STEP 14: PERFORMANCE COMPARISON")
print("=" * 70)

print(results_df.round(4).to_string(index=False))

# STEP 15: PLOT CONFUSION MATRICES

fig, axes = plt.subplots(1, 2, figsize=(12, 5))

for ax, model_name, predictions in zip(
    axes,
    ["Gaussian Naive Bayes", "Logistic Regression"],
    [gnb_predictions, lr_predictions]
):
    cm = confusion_matrix(
        y_test,
        predictions,
        labels=[0, 1]
    )

    sns.heatmap(
        cm,
        annot=True,
        fmt="d",
        cmap="Blues",
        cbar=False,
        ax=ax,
        xticklabels=["No Diabetes", "Diabetes"],
        yticklabels=["No Diabetes", "Diabetes"]
    )

    ax.set_title(model_name)
    ax.set_xlabel("Predicted Label")
    ax.set_ylabel("Actual Label")

plt.suptitle("Confusion Matrix Comparison")
plt.tight_layout()
plt.show()

# STEP 16: PLOT ROC CURVES

gnb_fpr, gnb_tpr, _ = roc_curve(
    y_test,
    gnb_probabilities
)

lr_fpr, lr_tpr, _ = roc_curve(
    y_test,
    lr_probabilities
)

gnb_auc = roc_auc_score(y_test, gnb_probabilities)
lr_auc = roc_auc_score(y_test, lr_probabilities)

plt.figure(figsize=(8, 6))

plt.plot(
    gnb_fpr,
    gnb_tpr,
    label=f"Gaussian Naive Bayes (AUC = {gnb_auc:.3f})"
)

plt.plot(
    lr_fpr,
    lr_tpr,
    label=f"Logistic Regression (AUC = {lr_auc:.3f})"
)

plt.plot(
    [0, 1],
    [0, 1],
    linestyle="--",
    label="Random Classifier"
)

plt.xlabel("False Positive Rate")
plt.ylabel("True Positive Rate")
plt.title("ROC Curve: Diabetes Classification")
plt.legend()
plt.grid(True)
plt.tight_layout()
plt.show()

# STEP 17: COMPARE METRICS VISUALLY

metrics_to_plot = [
    "Accuracy",
    "Precision",
    "Recall",
    "Specificity",
    "F1-Score",
    "ROC-AUC"
]

results_df.set_index("Model")[metrics_to_plot].T.plot(
    kind="bar",
    figsize=(11, 6)
)

plt.title("Gaussian Naive Bayes vs Logistic Regression")
plt.ylabel("Score")
plt.ylim(0, 1.05)
plt.xticks(rotation=0)
plt.grid(axis="y", alpha=0.3)
plt.tight_layout()
plt.show()

# STEP 18: DISPLAY THE BETTER AUC MODEL

if gnb_auc > lr_auc:
    print("\nHigher ROC-AUC: Gaussian Naive Bayes")

elif lr_auc > gnb_auc:
    print("\nHigher ROC-AUC: Logistic Regression")

else:
    print("\nBoth models have equal ROC-AUC.")

print("\nExperiment completed successfully.")