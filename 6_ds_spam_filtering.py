# ============================================================
# STEP 1: IMPORT REQUIRED LIBRARIES
# ============================================================

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.pipeline import Pipeline

from sklearn.linear_model import LogisticRegression
from sklearn.tree import DecisionTreeClassifier

from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    confusion_matrix,
    classification_report
)

# ============================================================
# STEP 2: LOAD THE SPAMBASE DATASET
# ============================================================

print("\n" + "=" * 65)
print("LAB EXPERIMENT 6: INTELLIGENT SPAM FILTERING")
print("=" * 65)

# SpamBase contains 57 email-related numerical features
# and one target column:
# 1 = Spam
# 0 = Not Spam (Ham)

# Load the dataset directly from a commonly used CSV copy.
# Internet access is required.

dataset_url = (
    "https://raw.githubusercontent.com/"
    "ayarekarpratik369/dataset/main/6_spambase.csv"
)

# This URL contains a different spam dataset with text columns,
# so instead we use the UCI-format SpamBase data below.

dataset_url = (
    "https://archive.ics.uci.edu/ml/machine-learning-databases/"
    "spambase/spambase.data"
)

# Official dataset has no column headers.
# The final column is the target label.

feature_names = [
    "word_freq_make", "word_freq_address", "word_freq_all",
    "word_freq_3d", "word_freq_our", "word_freq_over",
    "word_freq_remove", "word_freq_internet", "word_freq_order",
    "word_freq_mail", "word_freq_receive", "word_freq_will",
    "word_freq_people", "word_freq_report", "word_freq_addresses",
    "word_freq_free", "word_freq_business", "word_freq_email",
    "word_freq_you", "word_freq_credit", "word_freq_your",
    "word_freq_font", "word_freq_000", "word_freq_money",
    "word_freq_hp", "word_freq_hpl", "word_freq_george",
    "word_freq_650", "word_freq_lab", "word_freq_labs",
    "word_freq_telnet", "word_freq_857", "word_freq_data",
    "word_freq_415", "word_freq_85", "word_freq_technology",
    "word_freq_1999", "word_freq_parts", "word_freq_pm",
    "word_freq_direct", "word_freq_cs", "word_freq_meeting",
    "word_freq_original", "word_freq_project", "word_freq_re",
    "word_freq_edu", "word_freq_table", "word_freq_conference",
    "char_freq_semicolon", "char_freq_parenthesis",
    "char_freq_bracket", "char_freq_exclamation",
    "char_freq_dollar", "char_freq_hash",
    "capital_run_length_average",
    "capital_run_length_longest",
    "capital_run_length_total"
]

column_names = feature_names + ["target"]

df = pd.read_csv(dataset_url, header=None, names=column_names)

print("\nDataset loaded successfully!")

# ============================================================
# STEP 3: EXPLORE THE DATASET
# ============================================================

print("\nSTEP 3: DATASET EXPLORATION")
print("-" * 65)

print("\nFirst Five Records:")
print(df.head())

print("\nDataset Shape:")
print(df.shape)

print("\nDataset Information:")
df.info()

print("\nMissing Values:")
print(df.isnull().sum().sum())

print("\nSpam and Non-Spam Counts:")
print(df["target"].value_counts().rename(index={
    0: "Not Spam",
    1: "Spam"
}))

# ============================================================
# STEP 4: VISUALIZE CLASS DISTRIBUTION
# ============================================================

print("\nSTEP 4: CLASS DISTRIBUTION")
print("-" * 65)

class_counts = df["target"].value_counts().sort_index()

plt.figure(figsize=(7, 5))

plt.bar(
    ["Not Spam", "Spam"],
    [class_counts.get(0, 0), class_counts.get(1, 0)]
)

plt.title("Distribution of Spam and Non-Spam Emails")
plt.xlabel("Email Category")
plt.ylabel("Number of Emails")
plt.tight_layout()
plt.show()

# ============================================================
# STEP 5: SEPARATE FEATURES AND TARGET
# ============================================================

print("\nSTEP 5: FEATURE AND TARGET SELECTION")
print("-" * 65)

# X contains all 57 input features.
# y contains the target:
# 0 = Not Spam
# 1 = Spam

X = df.drop(columns=["target"])
y = df["target"]

print("Number of Features:", X.shape[1])
print("Number of Records:", X.shape[0])

# ============================================================
# STEP 6: SPLIT DATA INTO TRAINING AND TESTING SETS
# ============================================================

print("\nSTEP 6: TRAIN-TEST SPLIT")
print("-" * 65)

# 80% training data and 20% testing data.
# stratify=y preserves the spam/non-spam proportion in each set.

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

print("Training Records:", X_train.shape[0])
print("Testing Records:", X_test.shape[0])

# ============================================================
# STEP 7: IMPLEMENT LOGISTIC REGRESSION
# ============================================================

print("\nSTEP 7: LOGISTIC REGRESSION")
print("-" * 65)

# Logistic Regression is a classification algorithm.
# StandardScaler scales features using training data only.
# Pipeline ensures scaling is fitted only on the training set.

logistic_model = Pipeline([
    ("scaler", StandardScaler()),
    ("classifier", LogisticRegression(
        max_iter=2000,
        random_state=42
    ))
])

# Train the model
logistic_model.fit(X_train, y_train)

# Predict test-set labels
logistic_predictions = logistic_model.predict(X_test)

print("Logistic Regression trained successfully!")

# ============================================================
# STEP 8: IMPLEMENT DECISION TREE CLASSIFIER
# ============================================================

print("\nSTEP 8: DECISION TREE CLASSIFIER")
print("-" * 65)

# A Decision Tree learns rules from feature values.
# max_depth limits tree complexity and helps reduce overfitting.

decision_tree_model = DecisionTreeClassifier(
    max_depth=10,
    random_state=42
)

# Train the model
decision_tree_model.fit(X_train, y_train)

# Predict test-set labels
tree_predictions = decision_tree_model.predict(X_test)

print("Decision Tree Classifier trained successfully!")

# ============================================================
# STEP 9: EVALUATE LOGISTIC REGRESSION
# ============================================================

print("\nSTEP 9: LOGISTIC REGRESSION EVALUATION")
print("-" * 65)

lr_accuracy = accuracy_score(y_test, logistic_predictions)

lr_precision = precision_score(
    y_test, logistic_predictions, zero_division=0
)

lr_recall = recall_score(
    y_test, logistic_predictions, zero_division=0
)

lr_f1 = f1_score(
    y_test, logistic_predictions, zero_division=0
)

print(f"Accuracy  : {lr_accuracy:.4f}")
print(f"Precision : {lr_precision:.4f}")
print(f"Recall    : {lr_recall:.4f}")
print(f"F1-Score  : {lr_f1:.4f}")

print("\nClassification Report:")
print(classification_report(
    y_test,
    logistic_predictions,
    target_names=["Not Spam", "Spam"],
    zero_division=0
))

# ============================================================
# STEP 10: EVALUATE DECISION TREE
# ============================================================

print("\nSTEP 10: DECISION TREE EVALUATION")
print("-" * 65)

dt_accuracy = accuracy_score(y_test, tree_predictions)

dt_precision = precision_score(
    y_test, tree_predictions, zero_division=0
)

dt_recall = recall_score(
    y_test, tree_predictions, zero_division=0
)

dt_f1 = f1_score(
    y_test, tree_predictions, zero_division=0
)

print(f"Accuracy  : {dt_accuracy:.4f}")
print(f"Precision : {dt_precision:.4f}")
print(f"Recall    : {dt_recall:.4f}")
print(f"F1-Score  : {dt_f1:.4f}")

print("\nClassification Report:")
print(classification_report(
    y_test,
    tree_predictions,
    target_names=["Not Spam", "Spam"],
    zero_division=0
))

# ============================================================
# STEP 11: DISPLAY CONFUSION MATRICES
# ============================================================

print("\nSTEP 11: CONFUSION MATRICES")
print("-" * 65)

# Confusion matrix:
# Rows = Actual classes
# Columns = Predicted classes

lr_cm = confusion_matrix(
    y_test,
    logistic_predictions,
    labels=[0, 1]
)

dt_cm = confusion_matrix(
    y_test,
    tree_predictions,
    labels=[0, 1]
)

fig, axes = plt.subplots(1, 2, figsize=(12, 5))

sns.heatmap(
    lr_cm,
    annot=True,
    fmt="d",
    cmap="Blues",
    xticklabels=["Not Spam", "Spam"],
    yticklabels=["Not Spam", "Spam"],
    ax=axes[0]
)

axes[0].set_title("Logistic Regression Confusion Matrix")
axes[0].set_xlabel("Predicted Class")
axes[0].set_ylabel("Actual Class")

sns.heatmap(
    dt_cm,
    annot=True,
    fmt="d",
    cmap="Greens",
    xticklabels=["Not Spam", "Spam"],
    yticklabels=["Not Spam", "Spam"],
    ax=axes[1]
)

axes[1].set_title("Decision Tree Confusion Matrix")
axes[1].set_xlabel("Predicted Class")
axes[1].set_ylabel("Actual Class")

plt.tight_layout()
plt.show()

# ============================================================
# STEP 12: COMPARE BOTH CLASSIFICATION MODELS
# ============================================================

print("\nSTEP 12: FINAL MODEL COMPARISON")
print("-" * 65)

comparison = pd.DataFrame({
    "Model": [
        "Logistic Regression",
        "Decision Tree"
    ],
    "Accuracy": [
        lr_accuracy,
        dt_accuracy
    ],
    "Precision": [
        lr_precision,
        dt_precision
    ],
    "Recall": [
        lr_recall,
        dt_recall
    ],
    "F1-Score": [
        lr_f1,
        dt_f1
    ]
})

print(comparison.round(4).to_string(index=False))

# ============================================================
# STEP 13: VISUALIZE MODEL PERFORMANCE
# ============================================================

print("\nSTEP 13: MODEL PERFORMANCE COMPARISON")
print("-" * 65)

metrics = ["Accuracy", "Precision", "Recall", "F1-Score"]

comparison.set_index("Model")[metrics].plot(
    kind="bar",
    figsize=(11, 6)
)

plt.title("Logistic Regression vs Decision Tree")
plt.xlabel("Classification Model")
plt.ylabel("Score")
plt.ylim(0, 1.05)
plt.xticks(rotation=0)
plt.legend(loc="lower right")
plt.tight_layout()
plt.show()

# ============================================================
# STEP 14: FINAL CONCLUSION
# ============================================================

print("\nSTEP 14: FINAL CONCLUSION")
print("=" * 65)

if lr_f1 > dt_f1:
    print("Logistic Regression achieved the higher F1-score.")
elif dt_f1 > lr_f1:
    print("Decision Tree achieved the higher F1-score.")
else:
    print("Both models achieved the same F1-score.")

print("\nFinal Comparison:")
print(comparison.round(4).to_string(index=False))

print("\nInterpretation:")
print("- Accuracy measures overall correct predictions.")
print("- Precision measures how many predicted spam emails were spam.")
print("- Recall measures how many actual spam emails were detected.")
print("- F1-score balances precision and recall.")

print(
    "\nFor spam filtering, recall is important because low recall "
    "means more spam emails go undetected. Precision is also important "
    "because low precision means legitimate emails may be marked as spam."
)

print("\nLAB EXPERIMENT 6 COMPLETED SUCCESSFULLY!")
print("=" * 65)