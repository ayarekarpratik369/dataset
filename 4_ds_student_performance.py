# Mean = Sum of observations / Number of observations

def calculate_mean(data):
    total = 0

    for value in data:
        total += value

    return total / len(data)


# Median = Middle value of sorted observations

def calculate_median(data):
    sorted_data = sorted(data)
    n = len(sorted_data)

    if n % 2 == 1:
        return sorted_data[n // 2]

    return (sorted_data[n // 2 - 1] + sorted_data[n // 2]) / 2


# Mode = Value(s) with the highest frequency

def calculate_mode(data):
    frequency = {}

    for value in data:
        if value in frequency:
            frequency[value] += 1
        else:
            frequency[value] = 1

    highest_frequency = 0

    for value in frequency:
        if frequency[value] > highest_frequency:
            highest_frequency = frequency[value]

    modes = []

    for value in frequency:
        if frequency[value] == highest_frequency:
            modes.append(value)

    return modes


# Population Variance = Sum of squared deviations / N

def calculate_variance(data):
    mean_value = calculate_mean(data)
    squared_sum = 0

    for value in data:
        squared_sum += (value - mean_value) ** 2

    return squared_sum / len(data)


# Standard Deviation = Square root of variance

def calculate_std(data):
    return math.sqrt(calculate_variance(data))

