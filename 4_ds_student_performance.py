# STEP 8: T-TEST EXAMPLE 1
#
# Student scores:
# 68, 72, 75, 70, 69, 74, 71, 73, 67, 71
#
# Hypothesized population mean = 70
# n = 10, degrees of freedom = 9
# Critical t-value = +/- 2.262
#
# Formula:
# t = (Sample Mean - Hypothesized Mean) /
#     (Sample SD / sqrt(n))
#
# Sample variance = Sum of squared deviations / (n - 1)

print("\n\nSTEP 8: T-TEST EXAMPLE 1")

scores = [68, 72, 75, 70, 69, 74, 71, 73, 67, 71]

hypothesized_mean = 70
n = len(scores)

sample_mean = calculate_mean(scores)

squared_sum = 0

for value in scores:
    squared_sum += (value - sample_mean) ** 2

sample_variance = squared_sum / (n - 1)
sample_std = math.sqrt(sample_variance)

standard_error = sample_std / math.sqrt(n)

t_value = (sample_mean - hypothesized_mean) / standard_error

critical_t = 2.262

print("Sample Mean:", round(sample_mean, 4))
print("Sample Variance:", round(sample_variance, 4))
print("Sample Standard Deviation:", round(sample_std, 4))
print("Calculated T-value:", round(t_value, 4))

if abs(t_value) > critical_t:
    print("Decision: Reject the null hypothesis.")
else:
    print("Decision: Fail to reject the null hypothesis.")

