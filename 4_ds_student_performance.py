# STEP 6: Z-TEST EXAMPLE 1
#
# A sample of 36 students has a mean score of 74.
# Population mean = 70, population SD = 12.
# Test at 5% significance level, two-tailed.
#
# Formula:
# Z = (Sample Mean - Population Mean) /
#     (Population SD / sqrt(n))
#
# Critical values = +/- 1.96

print("\n\nSTEP 6: Z-TEST EXAMPLE 1")

population_mean = 70
sample_mean = 74
population_std = 12
n = 36
critical_z = 1.96

standard_error = population_std / math.sqrt(n)

z_value = (sample_mean - population_mean) / standard_error

print("Sample Mean:", sample_mean)
print("Population Mean:", population_mean)
print("Standard Error:", round(standard_error, 4))
print("Calculated Z-value:", round(z_value, 4))

if abs(z_value) > critical_z:
    print("Decision: Reject the null hypothesis.")
else:
    print("Decision: Fail to reject the null hypothesis.")

