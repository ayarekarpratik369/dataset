# ============================================================
# PROJECT: BOSTON HOUSE PRICE PREDICTION
# Dataset: Boston Housing
#
# MODELS:
# 1. Linear Regression (Baseline Model)
# 2. Random Forest Regression (Advanced Model)
#
# EVALUATION METRICS:
# 1. R² Score
# 2. Mean Absolute Error (MAE)
# 3. Root Mean Squared Error (RMSE)
#
# ADDITIONAL ANALYSIS:
# Correlation Matrix and Heatmap for Multicollinearity
# ============================================================


# ============================================================
# STEP 1: IMPORT REQUIRED LIBRARIES
# ============================================================

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.model_selection import train_test_split
from sklearn.linear_model import LinearRegression
from sklearn.ensemble import RandomForestRegressor

from sklearn.metrics import (
    r2_score,
    mean_absolute_error,
    mean_squared_error
)

# ============================================================
# STEP 2: LOAD THE BOSTON HOUSING DATASET
# ============================================================

print("\n" + "=" * 60)
print("BOSTON HOUSE PRICE PREDICTION")
print("=" * 60)

# Load a commonly used CSV copy of the Boston Housing dataset.
# Internet access is required for this step.

dataset_url = (
    "https://raw.githubusercontent.com/"
    "ayarekarpratik369/dataset/main/5_boston_housing.csv"
)

df = pd.read_csv(dataset_url)

print("\nSTEP 2: Dataset Loaded Successfully")
print("-" * 60)

# ============================================================
# STEP 3: EXPLORE THE DATASET
# ============================================================

print("\nSTEP 3: DATASET EXPLORATION")
print("-" * 60)

# Display the first five rows
print("\nFirst Five Rows:")
print(df.head())

# Display the number of rows and columns
print("\nDataset Shape:")
print(df.shape)

# Display column names and data types
print("\nDataset Information:")
df.info()

# Check for missing values
print("\nMissing Values in Each Column:")
print(df.isnull().sum())

# Display basic statistical information
print("\nStatistical Summary:")
print(df.describe())

# ============================================================
# STEP 4: IDENTIFY FEATURES AND TARGET VARIABLE
# ============================================================

print("\nSTEP 4: FEATURE AND TARGET SELECTION")
print("-" * 60)

# The target variable is medv, representing median house value.
# All remaining columns are used as input features.

target_column = "medv"

X = df.drop(columns=[target_column])
y = df[target_column]

print("\nInput Features:")
print(X.columns.tolist())

print("\nTarget Variable:", target_column)

print("\nNumber of Input Features:", X.shape[1])
print("Number of Records:", X.shape[0])

# ============================================================
# STEP 5: CHECK MULTICOLLINEARITY USING CORRELATION MATRIX
# ============================================================

print("\nSTEP 5: MULTICOLLINEARITY ANALYSIS")
print("-" * 60)

# Correlation matrix measures linear relationships between columns.
# Correlations close to +1 or -1 indicate strong linear relationships.

correlation_matrix = X.corr()

print("\nCorrelation Matrix:")
print(correlation_matrix.round(2))

# Plot the correlation heatmap
plt.figure(figsize=(14, 10))

sns.heatmap(
    correlation_matrix,
    annot=True,
    cmap="coolwarm",
    fmt=".2f",
    linewidths=0.5
)

plt.title("Correlation Heatmap - Boston Housing Features")
plt.tight_layout()
plt.show()


# Identify strongly correlated feature pairs.
# The absolute correlation threshold is 0.80.
# Each pair is reported only once.

print("\nStrongly Correlated Feature Pairs (|correlation| >= 0.80):")

strong_pairs_found = False

for i in range(len(correlation_matrix.columns)):
    for j in range(i + 1, len(correlation_matrix.columns)):

        correlation_value = correlation_matrix.iloc[i, j]

        if abs(correlation_value) >= 0.80:
            feature_1 = correlation_matrix.columns[i]
            feature_2 = correlation_matrix.columns[j]

            print(
                f"{feature_1} and {feature_2}: "
                f"{correlation_value:.3f}"
            )

            strong_pairs_found = True

if not strong_pairs_found:
    print("No feature pairs crossed the selected threshold.")

print(
    "\nNote: Pairwise correlation is a useful screening method, "
    "but it does not detect every form of multicollinearity."
)

# ============================================================
# STEP 6: SPLIT THE DATASET INTO TRAINING AND TESTING SETS
# ============================================================

print("\nSTEP 6: TRAIN-TEST SPLIT")
print("-" * 60)

# 80% of the data is used for training.
# 20% of the data is used for testing.
# random_state=42 makes the split reproducible.

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42
)

print("Training Records:", X_train.shape[0])
print("Testing Records:", X_test.shape[0])

print("\nTraining and testing datasets created successfully.")

# ============================================================
# STEP 7: IMPLEMENT LINEAR REGRESSION
# ============================================================

print("\nSTEP 7: LINEAR REGRESSION MODEL")
print("-" * 60)

# Linear Regression is the baseline model.
# It estimates a linear relationship between features and house prices.

linear_model = LinearRegression()

# Train the model
linear_model.fit(X_train, y_train)

# Predict house prices on unseen test data
linear_predictions = linear_model.predict(X_test)

print("Linear Regression model trained successfully.")

print("\nFirst 10 Actual House Prices:")
print(y_test.head(10).to_numpy())

print("\nFirst 10 Predicted House Prices:")
print(np.round(linear_predictions[:10], 2))

# ============================================================
# STEP 8: IMPLEMENT RANDOM FOREST REGRESSION
# ============================================================

print("\nSTEP 8: RANDOM FOREST REGRESSION MODEL")
print("-" * 60)

# Random Forest combines predictions from multiple decision trees.
# It can learn nonlinear relationships between features and prices.

random_forest_model = RandomForestRegressor(
    n_estimators=200,
    random_state=42,
    n_jobs=-1
)

# Train the model
random_forest_model.fit(X_train, y_train)

# Predict house prices on unseen test data
random_forest_predictions = random_forest_model.predict(X_test)

print("Random Forest Regression model trained successfully.")

print("\nFirst 10 Actual House Prices:")
print(y_test.head(10).to_numpy())

print("\nFirst 10 Predicted House Prices:")
print(np.round(random_forest_predictions[:10], 2))

# ============================================================
# STEP 9: EVALUATE BOTH MODELS
# ============================================================

print("\nSTEP 9: MODEL EVALUATION")
print("-" * 60)

# Metric 1: R² Score
# Higher is generally better.
# A score of 1.0 indicates perfect predictions.
# A score below 0 means the model performs worse than
# predicting the test-set target mean.

# Metric 2: MAE
# Mean Absolute Error measures average absolute prediction error.
# Lower is better.

# Metric 3: RMSE
# Root Mean Squared Error penalizes larger errors more heavily.
# Lower is better.

# -------------------------
# Evaluate Linear Regression
# -------------------------

linear_r2 = r2_score(y_test, linear_predictions)

linear_mae = mean_absolute_error(
    y_test,
    linear_predictions
)

linear_rmse = np.sqrt(
    mean_squared_error(y_test, linear_predictions)
)


# -------------------------
# Evaluate Random Forest
# -------------------------

rf_r2 = r2_score(y_test, random_forest_predictions)

rf_mae = mean_absolute_error(
    y_test,
    random_forest_predictions
)

rf_rmse = np.sqrt(
    mean_squared_error(y_test, random_forest_predictions)
)

# ============================================================
# STEP 10: DISPLAY INDIVIDUAL MODEL RESULTS
# ============================================================

print("\nLINEAR REGRESSION RESULTS")
print("-" * 40)

print(f"R² Score : {linear_r2:.4f}")
print(f"MAE      : {linear_mae:.4f}")
print(f"RMSE     : {linear_rmse:.4f}")


print("\nRANDOM FOREST REGRESSION RESULTS")
print("-" * 40)

print(f"R² Score : {rf_r2:.4f}")
print(f"MAE      : {rf_mae:.4f}")
print(f"RMSE     : {rf_rmse:.4f}")

# ============================================================
# STEP 11: FINAL COMPARISON TABLE
# ============================================================

print("\nSTEP 11: FINAL MODEL COMPARISON")
print("-" * 60)

comparison = pd.DataFrame({
    "Model": [
        "Linear Regression",
        "Random Forest Regression"
    ],

    "R2 Score": [
        linear_r2,
        rf_r2
    ],

    "MAE": [
        linear_mae,
        rf_mae
    ],

    "RMSE": [
        linear_rmse,
        rf_rmse
    ]
})

print(comparison.round(4).to_string(index=False))

# ============================================================
# STEP 12: VISUALIZE MODEL PERFORMANCE
# ============================================================

print("\nSTEP 12: MODEL PERFORMANCE VISUALIZATION")
print("-" * 60)

# Plot the comparison of all three evaluation metrics.

metrics = ["R2 Score", "MAE", "RMSE"]

fig, axes = plt.subplots(1, 3, figsize=(15, 5))

for i, metric in enumerate(metrics):

    axes[i].bar(
        comparison["Model"],
        comparison[metric]
    )

    axes[i].set_title(f"Model Comparison - {metric}")
    axes[i].set_ylabel(metric)
    axes[i].tick_params(axis="x", rotation=20)

    # Display the values above the bars
    for bar in axes[i].patches:
        height = bar.get_height()

        axes[i].annotate(
            f"{height:.3f}",
            (bar.get_x() + bar.get_width() / 2, height),
            ha="center",
            va="bottom",
            fontsize=9
        )

plt.tight_layout()
plt.show()

# ============================================================
# STEP 13: ACTUAL VS PREDICTED HOUSE PRICES
# ============================================================

print("\nSTEP 13: ACTUAL VS PREDICTED VISUALIZATION")
print("-" * 60)

# Compare actual prices with predictions from both models.
# Points closer to the diagonal line represent more accurate predictions.

plt.figure(figsize=(8, 6))

plt.scatter(
    y_test,
    linear_predictions,
    alpha=0.7,
    label="Linear Regression"
)

plt.scatter(
    y_test,
    random_forest_predictions,
    alpha=0.7,
    label="Random Forest"
)

# Reference line: perfect predictions would lie on this line.
min_price = min(
    y_test.min(),
    linear_predictions.min(),
    random_forest_predictions.min()
)

max_price = max(
    y_test.max(),
    linear_predictions.max(),
    random_forest_predictions.max()
)

plt.plot(
    [min_price, max_price],
    [min_price, max_price],
    linestyle="--",
    label="Perfect Prediction"
)

plt.xlabel("Actual House Prices")
plt.ylabel("Predicted House Prices")

plt.title("Actual vs Predicted House Prices")
plt.legend()
plt.tight_layout()
plt.show()

# ============================================================
# STEP 14: IDENTIFY THE BETTER-PERFORMING MODEL
# ============================================================

print("\nSTEP 14: FINAL CONCLUSION")
print("=" * 60)

# Higher R² is better.
# Lower MAE and RMSE are better.
# Use all three metrics instead of relying on R² alone.

if (
    rf_r2 > linear_r2
    and rf_mae < linear_mae
    and rf_rmse < linear_rmse
):

    print("Random Forest Regression performed better on all three metrics.")

elif (
    linear_r2 > rf_r2
    and linear_mae < rf_mae
    and linear_rmse < rf_rmse
):

    print("Linear Regression performed better on all three metrics.")

else:

    print("The models have mixed results across the three metrics.")
    print("Compare R², MAE, and RMSE to determine the trade-offs.")

print("\nFINAL METRICS:")
print(comparison.round(4).to_string(index=False))

print("\nPROJECT COMPLETED SUCCESSFULLY!")
print("=" * 60)